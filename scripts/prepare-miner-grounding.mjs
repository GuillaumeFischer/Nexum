// Read boot support points from the existing sprites; the art is not changed.
import {createRequire} from 'node:module';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {MINER_ATLASES,MINER_CELL} from '../games/deep-miners/client/new-miner-layout.js';
const require=createRequire(process.env.CANVAS_MODULE_ROOT?path.join(process.env.CANVAS_MODULE_ROOT,'package.json'):import.meta.url);
const {createCanvas,loadImage}=require('@napi-rs/canvas');
const client=fileURLToPath(new URL('../games/deep-miners/client/',import.meta.url)),ground={};
const {width,height}=MINER_CELL;
for(const [name,sheet]of Object.entries(MINER_ATLASES)){
 const image=await loadImage(path.join(client,sheet.asset)),c=createCanvas(image.width,image.height).getContext('2d');c.drawImage(image,0,0);
 const frames=[];
 for(let row=0;row<3;row++)for(let column=0;column<sheet.columns;column++){
  if(name==='idle'&&column===3){frames.push(null);continue;}
  const data=c.getImageData(column*width,row*height,width,height).data,bottoms=new Int16Array(width).fill(-1);
  // Boot leather has warm dark colours. Require a broad horizontal run to
  // exclude thin handles and ignore the neutral metal of picks and shovels.
  const brown=(x,y)=>{const i=(y*width+x)*4,r=data[i],g=data[i+1],b=data[i+2];return data[i+3]>160&&r>28&&r<205&&r>g*1.25&&g>b*1.28;};
  for(let y=140;y<height;y++){
   let start=-1;
   for(let x=40;x<=152;x++){
    if(x<152&&brown(x,y)){if(start<0)start=x;}
    else if(start>=0){if(x-start>=7)for(let xx=start;xx<x;xx++)bottoms[xx]=y;start=-1;}
   }
  }
  const support=Math.max(...bottoms);if(support<150)throw Error(`No boot support: ${name}/${row}/${column}`);
  const groups=[];let group=[];
  for(let x=40;x<=152;x++){
   if(x<152&&bottoms[x]>=support-20)group.push(x);
   else if(group.length){if(group.length>=7)groups.push(group);group=[];}
  }
  let contacts=groups.map(xs=>{
   const y=Math.max(...xs.map(x=>bottoms[x])),sole=xs.filter(x=>bottoms[x]>=y-2);
   const centre=sole.reduce((n,x)=>n+x,0)/sole.length,edge=sole.filter(x=>bottoms[x]===y);
   const x=edge.reduce((best,x)=>Math.abs(x-centre)<Math.abs(best-centre)?x:best,edge[0]);
   return {x,y,width:Math.max(7,Math.min(28,sole.at(-1)-sole[0]+1))};
  }).sort((a,b)=>b.y-a.y).slice(0,2);
  if(!contacts.length)throw Error(`No boot contacts: ${name}/${row}/${column}`);
  frames.push({y:Math.max(...contacts.map(p=>p.y)),contacts});
 }
 ground[name]=frames;
}
await fs.writeFile(path.join(client,'miner-ground-layout.js'),'// Boot support points in atlas pixels, generated by scripts/prepare-miner-grounding.mjs.\nexport const MINER_GROUND='+JSON.stringify(ground)+';\n');
console.log(JSON.stringify({sheets:Object.keys(ground).length,groundedFrames:Object.values(ground).flat().filter(Boolean).length,seatedFramesUnchanged:3}));
